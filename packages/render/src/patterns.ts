/** RGBA pixels of a pattern in two colours (0..1 channels), 8x8. Unknown names fall back to 50%. */
export function patternPixels(name: string, fg: { r: number; g: number; b: number; a: number }, bg: { r: number; g: number; b: number; a: number }): Uint8ClampedArray<ArrayBuffer> {
  const rows = PATTERNS[name] ?? PATTERNS.pct50!;
  const px = new Uint8ClampedArray(8 * 8 * 4);
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const on = ((rows[y] ?? 0) >> (7 - x)) & 1;
      const c = on ? fg : bg;
      const i = (y * 8 + x) * 4;
      px[i] = Math.round(c.r * 255);
      px[i + 1] = Math.round(c.g * 255);
      px[i + 2] = Math.round(c.b * 255);
      px[i + 3] = Math.round(c.a * 255);
    }
  }
  return px;
}
