// tools/anim/gen-presets.ts  -- extract one effect template per (presetClass, presetID, presetSubtype) from the corpus
//
//   node tools/anim/gen-presets.ts
//
// Reads every slide timing in decks PowerPoint wrote (docProps/app.xml says so), turns each preset effect into a
// template (packages/anim/src/template.ts: targets and outer timing taken out), and keeps, per preset, the template
// most of its occurrences agree on, recording the deck it came from. Writes packages/anim/src/presets.generated.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OpcPackage } from '../../packages/opc/src/index.ts';
import { PresentationDocument } from '../../packages/model/src/index.ts';
import { decodeXmlBytes } from '../../packages/xml/src/index.ts';
import { isContainer, parseTiming, walk } from '../../packages/anim/src/timing.ts';
import { templateOf, type PresetSource } from '../../packages/anim/src/template.ts';
import { corpusFiles, corpusName } from '../corpus/list.ts';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../packages/anim/src/presets.generated.ts');

/** The application that wrote a package, from docProps/app.xml. */
function application(pkg: OpcPackage): string {
  const part = pkg.getPart('/docProps/app.xml');
  if (!part) return '';
  try {
    return /<Application>([^<]*)<\/Application>/.exec(decodeXmlBytes(part.bytes).text)?.[1] ?? '';
  } catch {
    return '';
  }
}

interface Seen { template: Omit<PresetSource, 'occurrences' | 'agreeing'>; count: number; }

function main(): void {
  const byPreset = new Map<string, Map<string, Seen>>();
  let decks = 0;
  let effects = 0;
  for (const file of corpusFiles) {
    let doc: PresentationDocument;
    try {
      doc = new PresentationDocument(OpcPackage.open(new Uint8Array(readFileSync(file))));
    } catch {
      continue;
    }
    const app = application(doc.pkg);
    if (!/PowerPoint/.test(app) || /LibreOffice|Keynote|Google/i.test(app)) continue;
    decks++;
    for (const part of doc.slideParts()) {
      let el;
      try {
        el = doc.slide(part).timing;
      } catch {
        continue;
      }
      if (!el) continue;
      for (const n of walk(parseTiming(el).nodes)) {
        const c = n.cTn;
        if (!isContainer(n) || !c.presetClass || c.presetID === undefined) continue;
        const t = templateOf(n);
        if (!t) continue;
        effects++;
        const key = `${c.presetClass}|${c.presetID}|${c.presetSubtype ?? 0}`;
        // motion paths are drawn by hand each time: compare the rest of the template
        const form = JSON.stringify([t.attrs, t.behaviors.replace(/ (path|ptsTypes|rAng)="[^"]*"/g, '').replace(/<p:rCtr [^>]*\/>/g, '')]);
        let forms = byPreset.get(key);
        if (!forms) byPreset.set(key, (forms = new Map()));
        const seen = forms.get(form);
        if (seen) seen.count++;
        else {
          const { presetClass, presetID } = c;
          const source = `${corpusName(file)}#${part}`;
          forms.set(form, { count: 1, template: { presetClass, presetID, presetSubtype: c.presetSubtype ?? 0, ...t, source } });
        }
      }
    }
  }
  const out: PresetSource[] = [];
  for (const forms of byPreset.values()) {
    const all = [...forms.values()];
    const best = all.reduce((a, b) => (b.count > a.count ? b : a));
    out.push({ ...best.template, occurrences: all.reduce((s, f) => s + f.count, 0), agreeing: best.count });
  }
  out.sort((a, b) => a.presetClass.localeCompare(b.presetClass) || a.presetID - b.presetID || a.presetSubtype - b.presetSubtype);
  const body = out.map(p => `  ${JSON.stringify({
    presetClass: p.presetClass, presetID: p.presetID, presetSubtype: p.presetSubtype, duration: p.duration, attrs: p.attrs,
    occurrences: p.occurrences, agreeing: p.agreeing, source: p.source, behaviors: p.behaviors,
  })},`).join('\n');
  writeFileSync(OUT, '// packages/anim/src/presets.generated.ts  -- GENERATED by tools/anim/gen-presets.ts. Do not edit.\n//\n' +
    `// ${out.length} effect templates from the ${effects} preset effects in the ${decks} corpus decks PowerPoint wrote: one per\n` +
    '// (presetClass, presetID, presetSubtype), the one most occurrences agree on (`agreeing` of `occurrences`; motion\n' +
    '// paths compared without their path), with the deck and slide it was taken from.\n' +
    '// Regenerate with `node tools/anim/gen-presets.ts`.\n' +
    "import type { PresetSource } from './template.ts';\n\n" +
    `export const GENERATED_PRESETS: readonly PresetSource[] = [\n${body}\n];\n`);
  console.log(`${decks} PowerPoint decks, ${effects} effects, ${out.length} presets -> ${OUT}`);
}

main();
